-- Fresh PostgreSQL schema. Existing databases are baselined at version 1 and
-- receive the additive/reconciliation migration in V2; no data is dropped.
CREATE TABLE device_states (
 device_id varchar(64) PRIMARY KEY,
 last_counter bigint NOT NULL,
 failed_attempts integer NOT NULL,
 revoked_at timestamp(6) with time zone
);

CREATE TABLE transactions (
 transaction_id varchar(36) PRIMARY KEY,
 amount_minor bigint NOT NULL,
 destination varchar(64) NOT NULL,
 currency varchar(3),
 status varchar(32) NOT NULL,
 created_at timestamp(6) with time zone NOT NULL,
 updated_at timestamp(6) with time zone NOT NULL,
 device_id varchar(64),
 expected_glyphs varchar(127),
 expires_at timestamp(6) with time zone,
 requester_subject varchar(255),
 execution_claimed_at timestamp(6) with time zone,
 verified_at timestamp(6) with time zone,
 audit_json text,
 audit_source varchar(64),
 prompt_version varchar(64),
 audited_at timestamp(6) with time zone,
 gemini_decision_reason varchar(40),
 gemini_decision_at timestamp(6) with time zone,
 bank_receipt_id varchar(64),
 bank_status varchar(64),
 bank_provider varchar(32),
 bank_outcome varchar(32),
 bank_reason varchar(40),
 bank_submitted_at timestamp(6) with time zone,
 bank_outcome_at timestamp(6) with time zone
);

CREATE TABLE audit_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 timestamp timestamp(6) with time zone NOT NULL,
 event_type varchar(32) NOT NULL,
 device_id varchar(64),
 transaction_id varchar(36),
 outcome varchar(16) NOT NULL,
 reason varchar(40) NOT NULL,
 actor_subject varchar(255)
);

CREATE INDEX idx_audit_events_timestamp ON audit_events (timestamp, id);
