package com.runevault;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.DriverManager;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

@Testcontainers(disabledWithoutDocker = true)
class PostgresMigrationTest {
 @Container static PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:17-alpine");

 private void schema(String name) throws Exception {
  try (var connection = DriverManager.getConnection(postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
       var statement = connection.createStatement()) {
   statement.execute("CREATE SCHEMA " + name);
  }
 }

 private String url(String schema) {
  return postgres.getJdbcUrl() + (postgres.getJdbcUrl().contains("?") ? "&" : "?") + "currentSchema=" + schema;
 }

 private void migrate(String schema) {
  Flyway.configure().dataSource(url(schema), postgres.getUsername(), postgres.getPassword())
   .schemas(schema).defaultSchema(schema).baselineOnMigrate(true).baselineVersion("1")
   .locations("classpath:db/migration").load().migrate();
 }

 @Test void initializesEmptyPostgres() throws Exception {
  schema("fresh_app");
  migrate("fresh_app");
  try (var connection = DriverManager.getConnection(url("fresh_app"), postgres.getUsername(), postgres.getPassword());
       var statement = connection.createStatement()) {
   for (String table : new String[] {"transactions", "device_states", "audit_events", "flyway_schema_history"}) {
    try (var rows = statement.executeQuery("SELECT count(*) FROM " + table)) {
     assertTrue(rows.next());
    }
   }
   try (var rows = statement.executeQuery("SELECT count(*) FROM flyway_schema_history WHERE success")) {
    rows.next();
    assertEquals(2, rows.getInt(1));
   }
  }
 }

 @Test void baselinesLegacyRowsWithoutLosingCountersClaimsOrAudits() throws Exception {
  schema("legacy_app");
  try (var connection = DriverManager.getConnection(url("legacy_app"), postgres.getUsername(), postgres.getPassword());
       var statement = connection.createStatement()) {
   statement.execute("CREATE TABLE device_states (device_id varchar(64) PRIMARY KEY, last_counter bigint NOT NULL, failed_attempts integer NOT NULL, revoked_at timestamptz)");
   statement.execute("CREATE TABLE transactions (transaction_id varchar(36) PRIMARY KEY, amount_minor bigint NOT NULL, destination varchar(64) NOT NULL, status varchar(32) NOT NULL, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, bank_status varchar(64), execution_claimed_at timestamptz, verified_at timestamptz, CONSTRAINT transactions_status_check CHECK (status IN ('PENDING','SIMULATED','VERIFIED','EXECUTING','EXECUTED')))");
   statement.execute("CREATE TABLE audit_events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, timestamp timestamptz NOT NULL, event_type varchar(32) NOT NULL, outcome varchar(16) NOT NULL, reason varchar(40) NOT NULL)");
   statement.execute("INSERT INTO device_states VALUES ('slab-01',42,5,CURRENT_TIMESTAMP)");
   statement.execute("INSERT INTO transactions VALUES ('claimed',50000,'acct-999','EXECUTING',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,NULL,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)");
   statement.execute("INSERT INTO audit_events (timestamp,event_type,outcome,reason) VALUES (CURRENT_TIMESTAMP,'EXECUTION_CLAIM','APPROVED','EXECUTION_CLAIMED')");
  }
  migrate("legacy_app");
  try (var connection = DriverManager.getConnection(url("legacy_app"), postgres.getUsername(), postgres.getPassword());
       var statement = connection.createStatement()) {
   try (var rows = statement.executeQuery("SELECT last_counter,failed_attempts,revoked_at IS NOT NULL FROM device_states WHERE device_id='slab-01'")) {
    assertTrue(rows.next());
    assertEquals(42, rows.getLong(1));
    assertEquals(5, rows.getInt(2));
    assertTrue(rows.getBoolean(3));
   }
   try (var rows = statement.executeQuery("SELECT status,execution_claimed_at IS NOT NULL,verified_at IS NOT NULL,currency FROM transactions WHERE transaction_id='claimed'")) {
    assertTrue(rows.next());
    assertEquals("EXECUTING", rows.getString(1));
    assertTrue(rows.getBoolean(2));
    assertTrue(rows.getBoolean(3));
    assertEquals("USD", rows.getString(4));
   }
   try (var rows = statement.executeQuery("SELECT count(*) FROM audit_events WHERE reason='EXECUTION_CLAIMED'")) {
    rows.next();
    assertEquals(1, rows.getInt(1));
   }
  }
 }
}
